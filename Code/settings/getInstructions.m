function [design] = getInstructions(keys, design, participantInfo)
% getInstructions  All texts shown to the subject (German or English).
%
%   design = getInstructions(ptb.Keys, design, participantInfo)
%
% participantInfo.language 'german' or 'english' (default). The key for
% house/face follows keys.house == keys.left (getKeyAssignment). Wording
% rules: short, directive sentences; the same terms everywhere (house/face,
% left/right/lower key, fixation cross/dot); the percept question and the
% "mixed" rule are identical in the main experiment and in the QUEST+
% calibration/test (questplus.instructionText uses design.perceptRule and
% design.fixDotRule).
% The "lower key" is ptb.Keys.accept.

if nargin < 2 || isempty(design)
    design = DataContainer();
end
if ~design.hasField('brTrainingDuration')
    design.brTrainingDuration = 60;   % s per presentation in binocularRivalryTraining
end
if ~design.hasField('waitTillStartDuration')
    design.waitTillStartDuration = 3;
end
if ~isfield(participantInfo, 'language')
    participantInfo.language = 'english';
end
houseLeft = keys.house == keys.left;

if strcmp(participantInfo.language, 'german')
    if houseLeft; leftImage = 'Haus'; rightImage = 'Gesicht'; else; leftImage = 'Gesicht'; rightImage = 'Haus'; end
    cont = 'Drücke eine beliebige Taste, um fortzufahren.';
    keyLines = [leftImage ': linke Taste\n' rightImage ': rechte Taste\n'];
    % percept question + mixed rule (also used by questplus.instructionText)
    design.perceptRule = [ ...
        'Drücke die Taste für das Bild, das du zuerst deutlich siehst:\n\n' ...
        keyLines '\n' ...
        'Siehst du keines der beiden Bilder deutlich (nur eine Mischung),\n' ...
        'drücke die untere Taste.\n\n' ...
        'Antworte so schnell und so genau wie möglich.\n\n'];   % [changed 2026-11-10] was: sobald du es weißt
    dotRule = [ ...
        'Auf den Bildern erscheint ein Fixationspunkt.\n' ...
        'Fixiere den Punkt, solange du nur einen siehst.\n' ...
        'Siehst du zwei Punkte, fixiere das Kreuz in der Mitte.\n\n'];   % [changed 2026-11-10] fixate (not follow)
    design.fixDotRule = dotRule;   % also used by questplus.instructionText (dual)
    rivalryIntro = 'Danach siehst du ein Haus und ein Gesicht, auf jedem Auge eines.\n\n';

    design.Introduction = [ ...
        'Vielen Dank für deine Teilnahme an unserer Studie.\n\n' cont];
    design.cueInstruction = [ ...
        'Jeder Durchgang beginnt mit einem Buchstaben (P, A, I oder x)\n' ...
        'und einem farbigen Fixationskreuz (bei x schwarz).\n\n' ...
        'Die Farben bedeuten:\n'];
    % [changed 2026-11-10] one reminder line per task (explained on the slides)
    design.taskInstruction = [ ...
        'Der Buchstabe sagt dir die Aufgabe, die Farbe des Kreuzes das Bild:\n\n' ...
        'P - Perzeption: nimm das blasse Bild wahr.\n' ...
        'A - Aufmerksamkeit: achte auf das Bild der Farbe.\n' ...
        'I - Imagination: stell dir das Bild der Farbe vor.\n' ...
        'x - Fixation: schau nur auf das Kreuz.\n\n' ...
        'Deine Augen bleiben dabei auf dem Kreuz.\n' ...
        'Die Aufgabe endet, wenn die Rivalität beginnt.\n\n' cont];
    design.reportInstructionReport = [rivalryIntro design.perceptRule cont];
    design.reportInstructionNoReport = [rivalryIntro dotRule ...
        'Drücke für die Bilder keine Taste.\n\n' cont];
    design.reportInstructionDual = [rivalryIntro design.perceptRule dotRule cont];
    % [added 2026-11-04, reworded 2026-11-04] "New part" screen at run 1 of a report
    % condition (perImAtOffline/Online, log.runNr == 1). The runs are blocked, so it
    % says that only the response to the house/face images (the rivalry) changes,
    % gives the new rule (dual: key rule AND dot rule on the same screen) and that
    % the P/A/I/x task (offline: and its 1-5 rating) stays the same.
    newPartHead = ['Ab jetzt reagierst du anders auf die Haus- und Gesichtsbilder.\n' ...
        'Sie kommen wie bisher nach der P/A/I/x-Aufgabe, auf jedem Auge eines.\n\n' ...
        'So reagierst du jetzt:\n\n'];
    noKey = 'Drücke für die Bilder keine Taste.\n\n';
    same      = 'Gleich bleiben: die P/A/I/x-Aufgabe und die Bewertung 1 - 5 danach.\n\n';
    sameFmri  = 'Gleich bleibt: die P/A/I/x-Aufgabe.\n\n';   % fMRI version: no rating
    design.newPartReport       = [newPartHead design.perceptRule same cont];
    design.newPartNoReport     = [newPartHead dotRule noKey same cont];
    design.newPartDual         = [newPartHead design.perceptRule dotRule same cont];
    design.newPartReportFmri   = [newPartHead design.perceptRule sameFmri cont];   % perImAtOnline
    design.newPartNoReportFmri = [newPartHead dotRule noKey sameFmri cont];         % perImAtOnline
    design.questionInstruction = [ ...
        'Danach erscheint "1 - 5?": Bewerte, wie gut du die Aufgabe (P, A, I oder x)\n' ...
        'gemacht hast - nicht die Rivalität.\n' ...
        '1 = nicht gut   ...   5 = sehr gut\n\n' ...
        'Drücke jede der 5 Tasten einmal, um ihre Zahl zu sehen.'];
    design.ratingKeyMissing = 'Noch:';
    design.ratingKeyDone    = 'Fertig.';
    taskLine = 'P Perzeption  |  A Aufmerksamkeit  |  I Imagination  |  x Fixation\n';
    % [changed 2026-11-10] reminder at the start of runs 2-5 (run 1 shows the task
    % figure): what to do with the images, the task letters, look at the cross
    % (was a separate screen, design.fixOnFixCross), the colours
    design.legendReminderInstructionReport = [ ...
        'Erinnerung:\n' keyLines 'Mischung: untere Taste\n' ...
        'So schnell und so genau wie möglich.\n\n' taskLine ...
        'Schau die ganze Zeit auf das Kreuz.\n\n' ...
        'Die Farben bedeuten:\n'];
    design.legendReminderInstructionNoReport = [ ...
        'Erinnerung:\n' 'Keine Taste in der Rivalität.\n\n' ...
        'In der Rivalität: fixiere den Punkt. Zwei Punkte: fixiere das Kreuz.\n' ...
        'Vor und nach der Rivalität: schau auf das Kreuz.\n\n' taskLine '\n' ...
        'Die Farben bedeuten:\n'];
    design.legendReminderInstructionDual = [ ...
        'Erinnerung:\n' keyLines 'Mischung: untere Taste\n' ...
        'So schnell und so genau wie möglich.\n\n' ...
        'In der Rivalität: fixiere den Punkt. Zwei Punkte: fixiere das Kreuz.\n' ...
        'Vor und nach der Rivalität: schau auf das Kreuz.\n\n' taskLine '\n' ...
        'Die Farben bedeuten:\n'];
    design.figureContinue = cont;   % text line under a task figure (display.stereo.figureInstruction)
    design.fixOnFixCross = [ ...
        'Schau zwischen den Durchgängen auf das Fixationskreuz.\n\n' cont];
    design.waitTillStart = ['Start in ' num2str(round(design.waitTillStartDuration)) ' s.\n\n'];
    design.waitForScanner = 'Gleich geht es los.\n\nBitte bleib ganz ruhig liegen.';   % fMRI: until the scanner trigger
    design.RunIsOver = [ ...
        'Dieser Durchlauf ist vorbei.\n\n' ...
        'Drücke eine beliebige Taste und warte auf die Versuchsleitung.'];

    %% Sustained rivalry training (binocularRivalryTraining)
    % [changed 2026-11-10] short screen + figure (instructions/figures/brtraining_*);
    % brTrainingInstructionFull only if the figure is missing
    design.brTrainingInstructionShort = [ ...
        'Gleich siehst du ' num2str(round(design.brTrainingDuration)) ' Sekunden lang ein Haus und ein Gesicht,\n' ...
        'auf jedem Auge eines. Das kommt zweimal.\n\n' ...
        'Reagiere so schnell und so genau wie möglich auf jeden Wechsel.\n\n' cont];
    design.brTrainingInstruction = [ ...
        'Gleich siehst du auf jedem Auge ein anderes Bild: ein Haus und ein Gesicht,\n' ...
        'zweimal für je ' num2str(round(design.brTrainingDuration)) ' Sekunden.\n\n' ...
        'Deine Wahrnehmung wechselt zwischen den Bildern.\n' ...
        'Halte die Taste gedrückt, solange du ein Bild deutlich siehst:\n\n' ...
        keyLines '\n' ...
        'Siehst du eine Mischung, halte die untere Taste gedrückt.\n' ...
        'Wechselt das Bild, wechsle die Taste.\n\n' ...
        'Schau die ganze Zeit auf das Fixationskreuz.\n\n' cont];
    % [added 2026-11-11] key reminder after the figure, before the start (BR training,
    % QUEST+ calibration and test): the start countdown follows without a key press
    design.brTrainingReminder = [ ...
        'Erinnerung:\n' ...
        'Halte die Taste gedrückt, solange du ein Bild deutlich siehst:\n\n' ...
        keyLines 'Mischung: untere Taste\n\n' ...
        'Wechselt das Bild, wechsle die Taste.\n' ...
        'Schau die ganze Zeit auf das Kreuz.\n\n' cont];
    design.calibrationReminder = [ ...
        'Erinnerung:\n' ...
        'Drücke die Taste für das Bild, das du zuerst deutlich siehst:\n\n' ...
        keyLines 'Mischung: untere Taste\n\n' ...
        'So schnell und so genau wie möglich,\n' ...
        'spätestens 2 s nach der Rivalität.\n' ...
        'Schau die ganze Zeit auf das Kreuz.\n\n' cont];
    %% Key binding training (keyBindingTraining)
    design.keyTrainingInstruction = [ ...
        'Gleich siehst du nacheinander ein Haus oder ein Gesicht.\n\n' ...
        'Drücke die passende Taste:\n' keyLines '\n' ...
        'Nach jeder Antwort siehst du, ob sie richtig war.\n\n' cont];
    design.feedbackCorrect   = 'richtig';
    design.feedbackIncorrect = 'falsch';
    %% Fixation-dot positions + dual task (presentFixDotLocations)
    % [changed 2026-11-10] split over three screens (presentFixDotLocations)
    design.fixDotDemo1 = ['Im nächsten Teil erscheint auf den Bildern ein Fixationspunkt.\n\n' cont];
    design.fixDotDemo2 = [ ...
        'Zuerst siehst du die 6 Positionen des Punkts:\n' ...
        'einzeln, dann alle zusammen, erst auf dem Haus, dann auf dem Gesicht.\n\n' ...
        'Weiter jeweils mit einer beliebigen Taste.'];
    design.fixDotDemo3 = ['Jetzt übst du die ganze Aufgabe in 7 Durchgängen.\n\n' cont];
    design.fixDotDemoInstruction = [design.fixDotDemo1];   % (old name, kept)
    %% Consent form
    design.consent = [ ...
        'Ich bestätige:\n\n' ...
        'Ich wurde über die Studie und den Ablauf aufgeklärt.\n' ...
        'Meine Fragen zur Studie wurden vollständig und\n' ...
        'zu meiner Zufriedenheit beantwortet.\n' ...
        'Ich willige ein, an dieser Studie zur visuellen Wahrnehmung teilzunehmen.\n\n' ...
        'Drücke eine beliebige Taste, um zu bestätigen.'];
else
    if houseLeft; leftImage = 'house'; rightImage = 'face'; else; leftImage = 'face'; rightImage = 'house'; end
    cont = 'Press any key to continue.';
    keyLines = [leftImage ': left key\n' rightImage ': right key\n'];
    % percept question + mixed rule (also used by questplus.instructionText)
    design.perceptRule = [ ...
        'Press the key for the image you see clearly first:\n\n' ...
        keyLines '\n' ...
        'If you do not see either image clearly (only a mixture),\n' ...
        'press the lower key.\n\n' ...
        'Answer as fast and as accurately as possible.\n\n'];   % [changed 2026-11-10] was: as soon as you know
    dotRule = [ ...
        'A fixation dot appears on the images.\n' ...
        'Fixate the dot as long as you see only one.\n' ...
        'If you see two dots, fixate the cross in the centre.\n\n'];   % [changed 2026-11-10] fixate (not follow)
    design.fixDotRule = dotRule;   % also used by questplus.instructionText (dual)
    rivalryIntro = 'Then you see a house and a face, one in each eye.\n\n';

    design.Introduction = [ ...
        'Thank you for taking part in our study.\n\n' cont];
    design.cueInstruction = [ ...
        'Each trial starts with a letter (P, A, I or x)\n' ...
        'and a coloured fixation cross (black for x).\n\n' ...
        'The colours mean:\n'];
    % [changed 2026-11-10] one reminder line per task (explained on the slides)
    design.taskInstruction = [ ...
        'The letter tells you the task, the colour of the cross the image:\n\n' ...
        'P - Perception: perceive the faint image.\n' ...
        'A - Attention: attend to the image of the colour.\n' ...
        'I - Imagery: imagine the image of the colour.\n' ...
        'x - Fixation: just look at the cross.\n\n' ...
        'Keep your eyes on the cross.\n' ...
        'The task ends when the rivalry begins.\n\n' cont];
    design.reportInstructionReport = [rivalryIntro design.perceptRule cont];
    design.reportInstructionNoReport = [rivalryIntro dotRule ...
        'Do not press a key for the images.\n\n' cont];
    design.reportInstructionDual = [rivalryIntro design.perceptRule dotRule cont];
    % [added 2026-11-04, reworded 2026-11-04] "New part" screen at run 1 of a report
    % condition (perImAtOffline/Online, log.runNr == 1). The runs are blocked, so it
    % says that only the response to the house/face images (the rivalry) changes,
    % gives the new rule (dual: key rule AND dot rule on the same screen) and that
    % the P/A/I/x task (offline: and its 1-5 rating) stays the same.
    newPartHead = ['From now on, you respond differently to the house and face images.\n' ...
        'They come after the P/A/I/x task as before, one in each eye.\n\n' ...
        'How to respond now:\n\n'];
    noKey = 'Do not press a key for the images.\n\n';
    same      = 'Unchanged: the P/A/I/x task and the 1 - 5 rating after it.\n\n';
    sameFmri  = 'Unchanged: the P/A/I/x task.\n\n';   % fMRI version: no rating
    design.newPartReport       = [newPartHead design.perceptRule same cont];
    design.newPartNoReport     = [newPartHead dotRule noKey same cont];
    design.newPartDual         = [newPartHead design.perceptRule dotRule same cont];
    design.newPartReportFmri   = [newPartHead design.perceptRule sameFmri cont];   % perImAtOnline
    design.newPartNoReportFmri = [newPartHead dotRule noKey sameFmri cont];         % perImAtOnline
    design.questionInstruction = [ ...
        'Then "1 - 5?" appears: rate how well you did the task (P, A, I or x),\n' ...
        'not the rivalry.\n' ...
        '1 = not well   ...   5 = very well\n\n' ...
        'Press each of the 5 keys once to see its number.'];
    design.ratingKeyMissing = 'Still to find:';
    design.ratingKeyDone    = 'Done.';
    taskLine = 'P Perception  |  A Attention  |  I Imagery  |  x Fixation\n';
    % [changed 2026-11-10] reminder at the start of runs 2-5 (see German version)
    design.legendReminderInstructionReport = [ ...
        'Reminder:\n' keyLines 'mixture: lower key\n' ...
        'As fast and as accurately as possible.\n\n' taskLine ...
        'Look at the cross the whole time.\n\n' ...
        'The colours mean:\n'];
    design.legendReminderInstructionNoReport = [ ...
        'Reminder:\n' 'No key during the rivalry.\n\n' ...
        'During the rivalry: fixate the dot. Two dots: fixate the cross.\n' ...
        'Before and after the rivalry: look at the cross.\n\n' taskLine '\n' ...
        'The colours mean:\n'];
    design.legendReminderInstructionDual = [ ...
        'Reminder:\n' keyLines 'mixture: lower key\n' ...
        'As fast and as accurately as possible.\n\n' ...
        'During the rivalry: fixate the dot. Two dots: fixate the cross.\n' ...
        'Before and after the rivalry: look at the cross.\n\n' taskLine '\n' ...
        'The colours mean:\n'];
    design.figureContinue = cont;   % text line under a task figure (display.stereo.figureInstruction)
    design.fixOnFixCross = [ ...
        'Between trials, look at the fixation cross.\n\n' cont];
    design.waitTillStart = ['Starting in ' num2str(round(design.waitTillStartDuration)) ' s.\n\n'];
    design.waitForScanner = 'The run starts in a moment.\n\nPlease keep still.';   % fMRI: until the scanner trigger
    design.RunIsOver = [ ...
        'This run is over.\n\n' ...
        'Press any key and wait for the experimenter.'];

    %% Sustained rivalry training (binocularRivalryTraining)
    % [changed 2026-11-10] short screen + figure (see German version)
    design.brTrainingInstructionShort = [ ...
        'You will see a house and a face for ' num2str(round(design.brTrainingDuration)) ' seconds,\n' ...
        'one in each eye. This comes twice.\n\n' ...
        'Respond to every change as fast and as accurately as possible.\n\n' cont];
    design.brTrainingInstruction = [ ...
        'You will see a different image in each eye: a house and a face,\n' ...
        'twice for ' num2str(round(design.brTrainingDuration)) ' seconds.\n\n' ...
        'Your percept switches between the images.\n' ...
        'Hold down the key as long as you see one image clearly:\n\n' ...
        keyLines '\n' ...
        'If you see a mixture, hold down the lower key.\n' ...
        'When the image changes, switch the key.\n\n' ...
        'Look at the fixation cross the whole time.\n\n' cont];
    % [added 2026-11-11] key reminder after the figure (see German version)
    design.brTrainingReminder = [ ...
        'Reminder:\n' ...
        'Hold down the key as long as you see one image clearly:\n\n' ...
        keyLines 'mixture: lower key\n\n' ...
        'When the image changes, switch the key.\n' ...
        'Look at the cross the whole time.\n\n' cont];
    design.calibrationReminder = [ ...
        'Reminder:\n' ...
        'Press the key for the image you see clearly first:\n\n' ...
        keyLines 'mixture: lower key\n\n' ...
        'As fast and as accurately as possible,\n' ...
        'at the latest 2 s after the rivalry.\n' ...
        'Look at the cross the whole time.\n\n' cont];
    %% Key binding training (keyBindingTraining)
    design.keyTrainingInstruction = [ ...
        'You will see a house or a face, one after another.\n\n' ...
        'Press the matching key:\n' keyLines '\n' ...
        'After each answer you see whether it was correct.\n\n' cont];
    design.feedbackCorrect   = 'correct';
    design.feedbackIncorrect = 'incorrect';
    %% Fixation-dot positions + dual task (presentFixDotLocations)
    % [changed 2026-11-10] split over three screens (presentFixDotLocations)
    design.fixDotDemo1 = ['In the next part a fixation dot appears on the images.\n\n' cont];
    design.fixDotDemo2 = [ ...
        'First you see the 6 positions of the dot:\n' ...
        'one by one, then all together, first on the house, then on the face.\n\n' ...
        'Press any key each time to go on.'];
    design.fixDotDemo3 = ['Now you practise the whole task in 7 trials.\n\n' cont];
    design.fixDotDemoInstruction = [design.fixDotDemo1];   % (old name, kept)
    %% Consent form
    design.consent = [ ...
        'I confirm that:\n\n' ...
        'I have been informed about the study and its procedure.\n' ...
        'My questions about the study were answered fully\n' ...
        'and to my satisfaction.\n' ...
        'I agree to take part in this study on visual perception.\n\n' ...
        'Press any key to confirm.'];
end

%% Task figures (instructions/figures, stimulusPreparation/makeInstructionFigures.py)
% [added 2026-11-10] one figure per report condition, in the subject's
% language, key mapping and cue colours; perImAtOffline shows it at run 1 of a
% block (and the dual one in the practice) with display.stereo.figureInstruction.
if strcmp(participantInfo.language, 'german'); figLang = 'de'; else; figLang = 'en'; end
if houseLeft; figKeys = 'houseL'; else; figKeys = 'houseR'; end
figColour = 'houseRed';
if design.hasField('houseColor') && design.hasField('conditionColors') && ...
        ~isequal(design.houseColor, design.conditionColors(1,:))
    figColour = 'houseTeal';
end
figName = @(c) sprintf('block_%s_%s_%s_%s.png', c, figLang, figKeys, figColour);
% [changed 2026-11-10] each part's figure also comes in steps (_step1 screens, _step2 + eyes,
% _step3 + keys, complete = + colours and P/A/I/x); BR training and calibration figures
figSteps = @(c) {strrep(figName(c), '.png', '_step1.png'), strrep(figName(c), '.png', '_step2.png'), ...
    strrep(figName(c), '.png', '_step3.png'), figName(c)};
design.instructionFigure = struct('report', figName('report'), 'noReport', figName('noReport'), ...
    'dual', figName('dual'), ...
    'brtraining', sprintf('brtraining_%s_%s.png', figLang, figKeys), ...
    'calibration', sprintf('calibration_%s_%s.png', figLang, figKeys));
design.instructionFigureSteps = struct('report', {figSteps('report')}, 'noReport', {figSteps('noReport')}, ...
    'dual', {figSteps('dual')});

design.cueTextPerception = 'P';
design.cueTextAttention  = 'A';
design.cueTextImagery    = 'I';
design.cueTextBaseline   = 'x';
design.finalQuestion     = ' 1 - 5?';
end
